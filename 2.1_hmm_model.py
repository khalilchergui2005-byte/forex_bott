import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.dates as mdates
from sklearn.mixture import GaussianMixture
from pathlib import Path

# 1. ????? ????????
df = pd.read_csv("data/eurusd_daily.csv", index_col="Date", parse_dates=True)
print(f"? ?? ????? {len(df)} ????")

# 2. ??????? ????????? ?? ???????
df["Return"] = df["close"].pct_change()
df["Range"] = (df["high"] - df["low"]) / df["close"]
df["Volatility"] = df["Return"].rolling(20).std()
df["Momentum"] = df["close"].pct_change(10)
df = df.dropna()

features = ["Return", "Range", "Volatility", "Momentum"]
X = df[features].values
print(f"?? ???????: {features}")

# 3. ????? ????? GMM (3 ????? ?????)
gmm = GaussianMixture(n_components=3, covariance_type="full", random_state=42, n_init=10)
df["State"] = gmm.fit_predict(X)

# 4. ????? ????? ??????? ????? ??? ????? ??????
state_returns = df.groupby("State")["Return"].mean().sort_values()
mapping = {
    state_returns.index[0]: -1,  # ????
    state_returns.index[1]:  0,  # ????
    state_returns.index[2]:  1   # ????
}
df["Regime"] = df["State"].map(mapping)
regime_names = {-1: "????", 0: "????", 1: "????"}

print("\n?? ????? ????? ?????:")
for regime in [-1, 0, 1]:
    count = (df["Regime"] == regime).sum()
    avg_ret = df[df["Regime"] == regime]["Return"].mean() * 100
    print(f"   {regime_names[regime]}: {count} ??? ({count/len(df)*100:.1f}%) | ????? ??????: {avg_ret:.4f}%")

# 5. ??? ??????? ????????? ???????
import joblib
Path("models").mkdir(exist_ok=True)
joblib.dump(gmm, "models/hmm_regime_model.pkl")
df.to_csv("data/eurusd_daily_with_regimes.csv")
print("\n?? ?? ??? ??????? ?? models/hmm_regime_model.pkl")
print("?? ?? ??? ???????? ??????? ?? data/eurusd_daily_with_regimes.csv")

# 6. ???
fig, ax = plt.subplots(figsize=(18, 7))
colors = {-1: "#ffcccc", 0: "#f0f0f0", 1: "#ccffcc"}
for regime, color in colors.items():
    mask = df["Regime"] == regime
    ax.fill_between(df.index, df["close"].min(), df["close"].max(), where=mask, color=color, alpha=0.3)
ax.plot(df.index, df["close"], linewidth=1.2, color="black")
ax.set_title("EUR/USD ?? ????? ????? ????? (HMM)", fontsize=14)
ax.set_ylabel("?????")
ax.xaxis.set_major_formatter(mdates.DateFormatter("%Y-%m"))
ax.xaxis.set_major_locator(mdates.MonthLocator(interval=3))
plt.setp(ax.xaxis.get_majorticklabels(), rotation=45)
ax.legend(handles=[
    plt.Rectangle((0,0),1,1, color="#ccffcc", label="????"),
    plt.Rectangle((0,0),1,1, color="#f0f0f0", label="????"),
    plt.Rectangle((0,0),1,1, color="#ffcccc", label="????")
])
plt.tight_layout()
fig.savefig("reports/2.1_hmm_regimes.png", dpi=150)
plt.close()
print("? ?? ??? ??????? ?? reports/2.1_hmm_regimes.png")
