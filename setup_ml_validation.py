code = r'''"""
validate_ml_strategy.py - Institutional Profitability Test
Trains ML model, filters signals, and runs full backtest to measure PF and Max DD.
"""
import pandas as pd
import numpy as np
import warnings
warnings.filterwarnings("ignore")

from institutional_data_handler import prepare_institutional_data
from volume_shock_detector import VolumeShockDetector
from feature_engineer import FeatureEngineer
from meta_labeler import MetaLabeler
from backtest_engine import dynamic_backtest

print("=" * 60)
print("   ML STRATEGY PROFITABILITY TEST (Fixed Instrument)")
print("=" * 60)

print("\n[1/5] Preparing Institutional Data...")
df = prepare_institutional_data()
detector = VolumeShockDetector()
df = detector.detect(df)

print("[2/5] Building Features V2...")
fe = FeatureEngineer()
enriched, feature_cols = fe.build_features(df)

print("[3/5] Creating Base Signal & Targets...")
ml = MetaLabeler()
enriched = ml.create_base_signal(enriched)
enriched = ml.create_triple_barrier_target(enriched)

# Split 80/20
split_idx = int(len(enriched) * 0.8)
train_data = enriched.iloc[:split_idx]
test_data = enriched.iloc[split_idx:].copy()

X_train = train_data[feature_cols]
y_train = train_data["target"]

print("[4/5] Training Meta-Labeler...")
ml.train(X_train, y_train)

# Generate predictions on Test set
probs = ml.model.predict_proba(test_data[feature_cols])[:, 1]
preds = (probs >= 0.4432).astype(int)  # Using optimal threshold

# Meta-Labeling: Only take trades where model says 1
test_data["ML_Signal"] = 0
# Buy signals
test_data.loc[(test_data["base_signal"] == 1) & (preds == 1), "ML_Signal"] = 1
# Sell signals
test_data.loc[(test_data["base_signal"] == -1) & (preds == 1), "ML_Signal"] = -1

total_trades = (test_data["ML_Signal"] != 0).sum()
print(f"Total Filtered Signals (ML Approved): {total_trades}")

if total_trades > 0:
    print("\n[5/5] Running Full Backtest with Real Costs...")
    res = dynamic_backtest(data=test_data, strategy_cols=['ML_Signal'], risk_percent=0.005, log_trades=False)
    trades, equity_curve = res[0], res[1]
    
    wins = [t for t in trades if t > 0]
    losses = [t for t in trades if t <= 0]
    
    pf = abs(sum(wins) / sum(losses)) if losses and sum(losses) != 0 else 0.0
    total_pnl = sum(trades)
    
    # Max Drawdown
    eq = pd.Series(equity_curve)
    peak = eq.expanding().max()
    dd = ((peak - eq) / peak).max() * 100
    
    print("\n" + "=" * 50)
    print("   FINAL PROFITABILITY REPORT")
    print("=" * 50)
    print(f"Total Trades Executed: {len(trades)}")
    print(f"Win Rate: {len(wins)/len(trades)*100:.2f}%")
    print(f"Profit Factor (PF): {pf:.2f}")
    print(f"Total PnL: ${total_pnl:.2f}")
    print(f"Max Drawdown: {dd:.2f}%")
    print("=" * 50)
    
    if pf > 1.0:
        print("\nVERDICT: STRATEGY IS PROFITABLE.")
    else:
        print("\nVERDICT: STRATEGY NEEDS MORE TUNING (PF < 1.0).")
else:
    print("No trades generated by ML model.")
'''
open("validate_ml_strategy.py", "w", encoding="utf-8").write(code)
print("SUCCESS: validate_ml_strategy.py created")

